import { describe, expect, it } from 'vitest';
import { detectSubscriptions, type HistoryRow } from '../src/lib/subscriptions';
import { categoryAnomalies, categoryStats, largeExpenses, savingInsights, savingsRate } from '../src/lib/insights';
import { parseReceiptText } from '../src/lib/receiptParse';

const row = (description: string, amount: number, date: string, extra: Partial<HistoryRow> = {}): HistoryRow => ({
	description, amount, date, type: 'expense', category: 'Intrattenimento', tags: [], ...extra
});

describe('detectSubscriptions', () => {
	const netflix = ['2026-05-03', '2026-06-03', '2026-07-03', '2026-08-03', '2026-09-03', '2026-10-03'].map((d) => row('NETFLIX.COM 123456', 12.99, d));

	it('finds a monthly subscription and proposes the next date', () => {
		const [s] = detectSubscriptions(netflix, new Set(), '2026-10-20');
		expect(s.frequency).toBe('monthly');
		expect(s.amount).toBe(12.99);
		expect(s.nextDate).toBe('2026-11-03');
	});
	it('ignores payees already set up as recurring', () => {
		expect(detectSubscriptions(netflix, new Set(['netflix com']), '2026-10-20')).toHaveLength(0);
	});
	it('ignores movements generated by recurring rules and transfers', () => {
		expect(detectSubscriptions(netflix.map((r) => ({ ...r, tags: ['Ricorrente'] })), new Set(), '2026-10-20')).toHaveLength(0);
	});
	it('does not flag irregular shopping', () => {
		const shop = ['2026-05-02', '2026-05-09', '2026-06-20', '2026-07-01', '2026-09-15'].map((d, i) => row('ESSELUNGA', 20 + i * 17, d, { category: 'Cibo' }));
		expect(detectSubscriptions(shop, new Set(), '2026-10-01')).toHaveLength(0);
	});
	it('drops subscriptions that stopped long ago', () => {
		expect(detectSubscriptions(netflix, new Set(), '2027-03-01')).toHaveLength(0);
	});
	it('finds a yearly charge with two occurrences', () => {
		const ins = [row('ASSICURAZIONE AUTO', 480, '2024-11-10'), row('ASSICURAZIONE AUTO', 492, '2025-11-12')];
		const [s] = detectSubscriptions(ins, new Set(), '2026-10-01');
		expect(s.frequency).toBe('yearly');
	});
});

describe('insights', () => {
	it('computes the savings rate', () => {
		expect(savingsRate(2000, 1500)).toBe(25);
		expect(savingsRate(0, 100)).toBeNull();
	});
	it('warns when the projection beats the average', () => {
		const out = savingInsights({ month: '2026-11', income: 2000, expense: 1500 }, [
			{ month: '2026-10', income: 2000, expense: 1000 }, { month: '2026-09', income: 2000, expense: 1100 }
		], 0.5);
		expect(out.some((i) => i.level === 'warn')).toBe(true);
	});
	it('flags a category running above its average', () => {
		const out = categoryAnomalies([{ category: 'Cibo', month: '2026-11', expense: 450 }],
			[{ category: 'Cibo', month: 'x', expense: 1200 }], 3, 0.5);
		expect(out).toHaveLength(1);
		expect(categoryAnomalies([{ category: 'Cibo', month: '2026-11', expense: 150 }], [{ category: 'Cibo', month: 'x', expense: 1200 }], 3, 0.5)).toHaveLength(0);
	});
	it('flags an outlier expense only with enough history', () => {
		const baseline = Array.from({ length: 20 }, (_, i) => ({ category: 'Shopping', amount: 40 + (i % 5) }));
		const recent = [{ description: 'TV', amount: 900, date: '2026-11-02', category: 'Shopping' }];
		expect(largeExpenses(recent, categoryStats(baseline))).toHaveLength(1);
		expect(largeExpenses(recent, categoryStats(baseline.slice(0, 3)))).toHaveLength(0);
	});
});

describe('parseReceiptText', () => {
	const text = `SUPERMERCATO ROSSI SRL
VIA ROMA 12 - MILANO
P.IVA 01234567890
12/11/2026 18:45
LATTE 1,29
PANE 2,10
SUBTOTALE 3,39
IVA 4% 0,13
TOTALE EURO 3,39
CONTANTI 5,00
RESTO 1,61`;
	it('extracts total, date and merchant', () => {
		expect(parseReceiptText(text)).toEqual({ amount: 3.39, date: '2026-11-12', merchant: 'SUPERMERCATO ROSSI SRL' });
	});
	it('handles thousands separators and falls back to the largest figure', () => {
		expect(parseReceiptText('Officina Bianchi\nRiparazione 1.234,50\n03-02-26').amount).toBe(1234.5);
		expect(parseReceiptText('Officina Bianchi\nRiparazione 1.234,50\n03-02-26').date).toBe('2026-02-03');
	});
	it('returns nulls for noise', () => {
		expect(parseReceiptText('..\n!!')).toEqual({ amount: null, date: null, merchant: null });
	});
});

import { mapBankTransaction, syncFrom } from '../src/lib/openbanking';

describe('open banking mapping', () => {
	it('maps an expense with counterparty and reason', () => {
		const m = mapBankTransaction({
			transactionId: 'abc', bookingDate: '2026-11-03',
			transactionAmount: { amount: '-45.20', currency: 'EUR' },
			creditorName: 'ESSELUNGA SPA', remittanceInformationUnstructured: 'PAGAMENTO POS 03/11'
		});
		expect(m).toMatchObject({ externalId: 'abc', date: '2026-11-03', amount: -45.2, description: 'ESSELUNGA SPA - PAGAMENTO POS 03/11' });
	});
	it('uses the debtor for incoming money and builds an id when the bank gives none', () => {
		const m = mapBankTransaction({ valueDate: '2026-11-05', transactionAmount: { amount: '1500.00' }, debtorName: 'ACME SRL', remittanceInformationUnstructured: 'Stipendio ottobre' });
		expect(m?.amount).toBe(1500);
		expect(m?.description).toContain('ACME SRL');
		expect(m?.externalId).toContain('2026-11-05');
	});
	it('skips rows without a date or with zero/garbage amounts', () => {
		expect(mapBankTransaction({ transactionAmount: { amount: '5' } })).toBeNull();
		expect(mapBankTransaction({ bookingDate: '2026-11-05', transactionAmount: { amount: '0.00' } })).toBeNull();
		expect(mapBankTransaction({ bookingDate: '2026-11-05', transactionAmount: { amount: 'abc' } })).toBeNull();
	});
	it('goes back 90 days the first time and overlaps 3 days afterwards', () => {
		expect(syncFrom(null, new Date('2026-11-16T10:00:00Z'))).toBe('2026-08-18');
		expect(syncFrom('2026-11-10T08:00:00Z', new Date('2026-11-16'))).toBe('2026-11-07');
	});
});

import { extractAuthCode, mapEnableBankingTransaction, sessionAccounts } from '../src/lib/openbanking';

describe('enable banking', () => {
	it('signs debits negative and uses the creditor as counterparty', () => {
		const m = mapEnableBankingTransaction({
			entry_reference: 'E1', booking_date: '2026-11-04', status: 'BOOK', credit_debit_indicator: 'DBIT',
			transaction_amount: { amount: '23.90', currency: 'EUR' }, creditor: { name: 'PAYPAL EUROPE' }, remittance_information: ['Pagamento', 'ordine 55']
		});
		expect(m).toMatchObject({ externalId: 'E1', date: '2026-11-04', amount: -23.9, description: 'PAYPAL EUROPE - Pagamento ordine 55' });
	});
	it('keeps credits positive and falls back to value date and note', () => {
		const m = mapEnableBankingTransaction({ value_date: '2026-11-05', credit_debit_indicator: 'CRDT', transaction_amount: { amount: '1500.00' }, debtor: { name: 'ACME' }, note: 'Stipendio' });
		expect(m?.amount).toBe(1500);
		expect(m?.description).toBe('ACME - Stipendio');
	});
	it('skips rows without date or amount', () => {
		expect(mapEnableBankingTransaction({ transaction_amount: { amount: '5' }, credit_debit_indicator: 'DBIT' })).toBeNull();
		expect(mapEnableBankingTransaction({ booking_date: '2026-11-05', transaction_amount: { amount: '0' } })).toBeNull();
	});
	it('extracts the code from the pasted address or a bare code', () => {
		expect(extractAuthCode('https://enablebanking.com/?state=abc&code=5f1c-AA_9.z#x')).toBe('5f1c-AA_9.z');
		expect(extractAuthCode('  5f1c-AA_9.zzzz ')).toBe('5f1c-AA_9.zzzz');
		expect(extractAuthCode('ciao')).toBeNull();
		expect(extractAuthCode('')).toBeNull();
	});
	it('reads accounts in both session shapes', () => {
		expect(sessionAccounts({ accounts: [{ uid: 'u1', account_id: { iban: 'IT60X0542811101000000123456' } }] })).toEqual([{ uid: 'u1', label: '…3456' }]);
		expect(sessionAccounts({ accounts: ['u2'], accounts_data: [{ uid: 'u2', account_id: { iban: 'IT00AAAA1111' } }] })).toEqual([{ uid: 'u2', label: '…1111' }]);
	});
});
